function packFor(meta){
 if(meta.family==='Poison')return 'poisons';
 if(meta.family==='Equipment')return 'equipment';
 if(meta.family==='Clan')return 'clans';
 if(meta.family==='Hijutsu')return 'hijutsu';
 return 'techniques';
}
function folderPath(meta,pack){
 if(meta.family==='Basic Jutsu')return ['Basic Jutsu'];
 if(['Kekkei Genkai','Kinjutsu'].includes(meta.family))return [meta.family,meta.owner,meta.kind];
 if(pack==='aptitudes')return meta.aptitudePath||['Unclassified Aptitudes'];
 if(pack==='poisons')return ['Consumable Poisons',`Category ${meta.category===undefined?'Unspecified':meta.category}`];
 if(pack==='equipment')return meta.equipmentPath||[meta.equipmentFolder||'Other Equipment'];
 return [meta.family==='Review'?'Association Review':meta.family==='General Powers'?'Non-Clan & Non-Hijutsu Powers':meta.owner,meta.family==='General Powers'?meta.owner:meta.kind,meta.family==='General Powers'?meta.kind:(meta.level?`Level ${meta.level}`:'Level Unspecified'),...(meta.family==='General Powers'?[meta.level?`Level ${meta.level}`:'Level Unspecified']:[])];
}
function weaponRows(data,file){
  if(file==='sns-weapon-library__weapons.json'){
   if(!data || typeof data!=='object' || Array.isArray(data))throw Error('Unexpected weapon library structure');
   return Object.entries(data).flatMap(([section,entries])=>{
    if(!Array.isArray(entries))return [];
    return entries.map((weapon,index)=>({...weapon,__snsWeaponSection:section,__snsWeaponIndex:index}));
   });
  }
  return Array.isArray(data)?data:Object.values(data).flatMap(x=>Array.isArray(x)?x:[]);
}
function weaponDescription(raw,section){
 const fields=[
  ['Weapon class',raw.group],['Size',raw.size],['Attack',raw.attack],
  ['Damage bonus',raw.damage],['Damage type',raw.dtype],['Critical range',raw.crit],
  ['Range',raw.range],['Price',raw.price],['Equipment slots',raw.slots],
  ['Units',raw.units],['Source',raw.advancedSource],['Pages',raw.advancedPages],['Notes',raw.note]
 ];
 return [`Weapon library: ${section}`, ...fields.filter(([k,v])=>v!==null&&v!==undefined&&v!=='').map(([k,v])=>`${k}: ${v}`)].join('\n');
}
