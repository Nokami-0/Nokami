async function folderFor(pack,path,cache){
 let parent=null;
 for(const name of path){
  const key=`${parent||'root'}::${name}`;
  if(cache.has(key)){parent=cache.get(key);continue;}
  let f=pack.folders.find(x=>x.name===name&&(x.folder?.id||null)===parent);
  if(!f)f=await Folder.create({name:clean(name),type:'Item',folder:parent,sorting:'a'},{pack:pack.collection});
  parent=f.id;cache.set(key,parent);
 }
 return parent;
}
async function buildSNSCompendiums(){
 if(!game.user.isGM)throw Error('GM permissions required');
 const report={added:0,removed:0,errors:[],categories:{},poisons:{},weapons:{}};
 const packs={};
 for(const [key,label] of Object.entries(SNS_PACKS)){
  let pack=game.packs.get(`world.sns-${key}`);
  if(!pack)pack=await CompendiumCollection.createCompendium({name:`sns-${key}`,label,type:'Item',package:'world',ownership:{PLAYER:'OBSERVER',ASSISTANT:'OWNER'}});
  if(pack.locked)await pack.configure({locked:false});packs[key]=pack;
 }
 // Only delete entries with this system's generated UID; never delete manual entries.
 for(const pack of Object.values(packs)){
  const docs=await pack.getDocuments();
  const ids=docs.filter(x=>x.flags?.[SNSC]?.compendiumUid).map(x=>x.id);
  if(ids.length){await Item.deleteDocuments(ids,{pack:pack.collection});report.removed+=ids.length;}
 }
 const cache=Object.fromEntries(Object.keys(packs).map(k=>[k,new Map()]));
 for(const [file,source,scope] of SNS_FILES){
  try{
   const r=await fetch(`systems/${SNSC}/integrated/data/${file}`);
   if(!r.ok)throw Error(`HTTP ${r.status}`);
   const data=await r.json();
   const rows=weaponRows(data,file);
   for(let i=0;i<rows.length;i++){
    const doc=normalize(rows[i],source,file,i,scope);if(!doc)continue;
    const key=doc.flags[SNSC].category;
    try{
     doc.folder=await folderFor(packs[key],folderPath(doc.flags[SNSC].hierarchy,key),cache[key]);
     await Item.create(doc,{pack:packs[key].collection});report.added++;
     report.categories[key]=(report.categories[key]||0)+1;
     if(key==='equipment'){const folder=doc.flags[SNSC].hierarchy.equipmentFolder;report.weapons[folder]=(report.weapons[folder]||0)+1;}
     if(key==='poisons'){const cat=String(rows[i].category??'Unspecified');report.poisons[cat]=(report.poisons[cat]||0)+1;}
    }catch(e){report.errors.push(`${file} / ${doc.name}: ${e.message}`);}
   }
  }catch(e){report.errors.push(`${file}: ${e.message}`);}
 }
 const ninpou=await buildNinpouCompendium();report.categories.ninpou=ninpou.total;
 await ensureHomebrewHijutsu();
 for(const pack of Object.values(packs))await pack.configure({locked:true});
 console.info('Shinobi compendium repair report',report);
 ui.notifications.info(`Shinobi compendiums: ${report.added} imported, ${report.errors.length} errors. See console for details.`);
 return report;
}
